"""Offline tests for cleanup_generated.py: it removes only Promptherder output."""
import io
import json
import os
import pathlib
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import cleanup_generated  # noqa: E402

MARK = "<!-- Auto-generated by promptherder — do not edit -->\n"


def write(root, rel, text):
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


class CleanupTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.tmp.name).resolve() / "repo"
        self.root.mkdir()
        self.git("init", "-q")
        write(self.root, "README.md", "tracked\n")
        write(self.root, ".claude/skills/tracked-skill/SKILL.md", MARK + "tracked generated copy\n")
        self.git("add", "-A")
        self.git("-c", "user.email=t@x", "-c", "user.name=t", "commit", "-qm", "base")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        subprocess.run(["git", "-C", str(self.root), *args], check=True, capture_output=True)

    def run_script(self, *args, env=None):
        out = io.StringIO()
        old = os.environ.copy()
        try:
            if env:
                os.environ.update(env)
            with redirect_stdout(out):
                cleanup_generated.main([str(self.root), *args])
        finally:
            os.environ.clear()
            os.environ.update(old)
        return out.getvalue()

    def test_removes_only_promptherder_output(self):
        write(self.root, ".claude/skills/review/SKILL.md", "---\nname: review\n---\n" + MARK + "body\n")
        write(self.root, ".claude/skills/mise/SKILL.md", "---\nname: mise\n---\nhand-written, no marker\n")
        write(self.root, ".claude/rules/guide.md", "---\npaths: ['**/*.ex']\n---\n" + MARK + "rule\n")
        write(self.root, ".claude/rules/mine.md", "my own rule\n")
        write(self.root, ".claude/settings.json", "{}\n")
        write(self.root, ".claude/worktrees/agent-1/file", "keep\n")
        write(self.root, "AGENTS.md", MARK + "\n# Hard Rules\n")
        write(self.root, "CLAUDE.md", "My notes\n" + MARK + "@AGENTS.md\n")
        output = self.run_script("--apply")
        self.assertFalse((self.root / ".claude/skills/review").exists())
        self.assertFalse((self.root / ".claude/rules/guide.md").exists())
        self.assertFalse((self.root / "AGENTS.md").exists())
        for kept in (".claude/skills/mise/SKILL.md", ".claude/rules/mine.md", ".claude/settings.json",
                     ".claude/worktrees/agent-1/file", "CLAUDE.md", ".claude/skills/tracked-skill/SKILL.md",
                     "README.md"):
            self.assertTrue((self.root / kept).exists(), kept)
        self.assertIn("left for you: .claude/skills/mise/SKILL.md", output)
        self.assertIn("left for you: CLAUDE.md", output)

    def test_manifest_and_herd_sources_are_evidence(self):
        write(self.root, ".agents/skills/old/SKILL.md", "no marker, but listed\n")
        write(self.root, ".promptherder/manifest.json",
              json.dumps({"artifacts": {".agents/skills/old/SKILL.md": {"hash": "x"}}}))
        write(self.root, ".promptherder/herds/compound-v/rules/browser.md", "source\n")
        write(self.root, ".agents/rules/browser.md", "antigravity copy without marker\n")
        write(self.root, ".agents/rules/unrelated.md", "keep\n")
        self.run_script("--apply")
        self.assertFalse((self.root / ".agents/skills/old").exists())
        self.assertFalse((self.root / ".agents/rules/browser.md").exists())
        self.assertTrue((self.root / ".agents/rules/unrelated.md").exists())

    def test_manifest_from_git_history(self):
        write(self.root, ".promptherder/manifest.json",
              json.dumps({"artifacts": {".claude/rules/x.md": {"hash": "x"}}}))
        self.git("add", "-A")
        self.git("-c", "user.email=t@x", "-c", "user.name=t", "commit", "-qm", "manifest")
        self.git("rm", "-q", ".promptherder/manifest.json")
        self.git("-c", "user.email=t@x", "-c", "user.name=t", "commit", "-qm", "drop manifest")
        write(self.root, ".claude/rules/x.md", "generated without marker\n")
        output = self.run_script("--apply")
        self.assertIn("manifest from git", output)
        self.assertFalse((self.root / ".claude/rules/x.md").exists())

    def test_preview_changes_nothing_and_lists_paths(self):
        write(self.root, ".claude/skills/review/SKILL.md", MARK + "body\n")
        output = self.run_script()
        self.assertIn("would remove: .claude/skills/review/SKILL.md", output)
        self.assertTrue((self.root / ".claude/skills/review/SKILL.md").exists())

    def test_symlinked_base_is_not_followed(self):
        outside = self.root.parent / "shared-skills"
        write(outside, "review/SKILL.md", MARK + "body\n")
        (self.root / ".agents").mkdir()
        os.symlink(outside, self.root / ".agents/skills")
        self.run_script("--apply")
        self.assertTrue((outside / "review/SKILL.md").exists())

    def test_git_failure_removes_nothing(self):
        write(self.root, ".claude/skills/review/SKILL.md", MARK + "body\n")
        with self.assertRaises(SystemExit):
            self.run_script("--apply", env={"GIT_DIR": "/nonexistent"})
        self.assertTrue((self.root / ".claude/skills/review/SKILL.md").exists())
        self.assertTrue((self.root / ".claude/skills/tracked-skill/SKILL.md").exists())

    def test_second_run_is_a_no_op(self):
        write(self.root, ".claude/skills/review/SKILL.md", MARK + "body\n")
        self.run_script("--apply")
        self.assertIn("removing 0 files", self.run_script("--apply"))


if __name__ == "__main__":
    unittest.main()
