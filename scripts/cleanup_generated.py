"""Remove Promptherder's generated output from a checkout that is moving to the plugins.

Usage:
    python3 -I scripts/cleanup_generated.py <checkout>           # preview: lists every path
    python3 -I scripts/cleanup_generated.py <checkout> --apply   # remove them

Run it in every existing checkout before pulling (or merging) the change that
retires Promptherder there: the generated files are untracked, so Claude Code and
Codex would keep loading the old skills and rules, and a newly tracked AGENTS.md
or CLAUDE.md can block the pull.

A file or folder is removed only when it is untracked, not a symlink, and there is
evidence Promptherder generated it:
- the Promptherder manifest lists it under .claude/skills/, .claude/rules/,
  .agents/ or .agent/ (if the manifest is already gone from the working tree, its
  last committed version in git history is used);
- it carries Promptherder's "Auto-generated by promptherder" marker near the top
  (skill folders: in their SKILL.md; AGENTS.md / CLAUDE.md: on the first line, so
  nothing hand-written sits above it);
- or, under .agents/{rules,workflows} or as a skills README, a file of the same
  name exists in a herd source under .promptherder/herds/ (older Antigravity
  copies carry no marker).
Everything else under those folders is listed as "left for you" and kept, as are
tracked files, .claude/settings*.json and .claude/worktrees/. The script stops
without touching anything if git can't read the checkout.
"""
import argparse
import json
import os
import pathlib
import shutil
import subprocess
import sys

MARKER = b"<!-- Auto-generated by promptherder"
GENERATED_DIRS = (".claude/skills/", ".claude/rules/", ".agents/", ".agent/")
SCAN_DIRS = (".claude/skills", ".claude/rules", ".agents", ".agent")
KEEP_PREFIXES = (".claude/worktrees/", ".claude/settings")
MARKER_LINES = 15


def git(root, *args):
    # The caller's GIT_DIR / GIT_WORK_TREE / GIT_INDEX_FILE could point git at another repository,
    # whose index would make this checkout's tracked files look untracked.
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_") or k.startswith(("GIT_CONFIG", "GIT_SSH"))}
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, env=env)


def has_marker(path, first_line_only=False):
    try:
        with open(path, "rb") as f:
            lines = f.read(8192).splitlines()
    except OSError:
        return False
    head = lines[:1] if first_line_only else lines[:MARKER_LINES]
    return any(line.lstrip().startswith(MARKER) for line in head)


def load_manifest(root):
    path = root / ".promptherder/manifest.json"
    if path.is_file() and not path.is_symlink():
        return parse_manifest(path.read_text(), path), "working tree"
    last = git(root, "log", "-1", "--format=%H", "--", ".promptherder/manifest.json").stdout.strip()
    for rev in ([last, f"{last}^"] if last else []):
        shown = git(root, "show", f"{rev}:.promptherder/manifest.json")
        if shown.returncode == 0:
            return parse_manifest(shown.stdout, f"{rev}:.promptherder/manifest.json"), f"git {rev}"
    return {}, "none"


def parse_manifest(text, where):
    try:
        return json.loads(text).get("artifacts") or {}
    except (ValueError, AttributeError) as e:
        sys.exit(f"{where}: unreadable Promptherder manifest ({e}); fix or remove it. Nothing removed")


def safe_relative(rel):
    parts = pathlib.PurePosixPath(rel)
    return not parts.is_absolute() and ".." not in parts.parts


def herd_source_names(root):
    names = set()
    herds = root / ".promptherder/herds"
    if herds.is_dir():
        for sub in ("rules", "workflows", "skills"):
            for f in herds.glob(f"*/{sub}/*"):
                if f.is_file():
                    names.add((sub, f.name))
    if (root / ".promptherder/hard-rules.md").is_file():
        names.add(("rules", "hard-rules.md"))
    return names


def plan(root):
    top = git(root, "rev-parse", "--show-toplevel")
    if top.returncode != 0 or pathlib.Path(top.stdout.strip()).resolve() != root:
        sys.exit(f"{root}: not the top of a git checkout git can read ({top.stderr.strip() or top.stdout.strip()}); nothing removed")
    listed = git(root, "ls-files", "-z")
    if listed.returncode != 0:
        sys.exit(f"{root}: git ls-files failed ({listed.stderr.strip()}); nothing removed")
    tracked = set(filter(None, listed.stdout.split("\0")))

    def is_tracked(rel):
        return rel in tracked or any(f.startswith(rel + "/") for f in tracked)

    def usable(path):
        rel = path.relative_to(root)
        parts = [root.joinpath(*rel.parts[:i]) for i in range(1, len(rel.parts) + 1)]
        return not any(p.is_symlink() for p in parts) and not is_tracked(str(rel))

    artifacts, source = load_manifest(root)
    remove, rejected = set(), []
    for rel in artifacts:
        if not safe_relative(rel):
            rejected.append(f"{rel} (manifest path outside the checkout, ignored)")
            continue
        path = root / rel
        if rel.startswith(GENERATED_DIRS) and path.is_file() and usable(path):
            remove.add(rel)
    for base in (".claude/skills", ".agents/skills", ".agent/skills"):
        top_dir = root / base
        if top_dir.is_dir() and not top_dir.is_symlink():
            for skill in top_dir.iterdir():
                if skill.is_dir() and usable(skill) and has_marker(skill / "SKILL.md"):
                    remove.add(str(skill.relative_to(root)))
    for base in (".claude/rules", ".agents/rules", ".agents/workflows", ".agent/rules", ".agent/workflows"):
        top_dir = root / base
        if top_dir.is_dir() and not top_dir.is_symlink():
            for f in top_dir.iterdir():
                if f.is_file() and usable(f) and has_marker(f):
                    remove.add(str(f.relative_to(root)))
    sources = herd_source_names(root)
    for base, kind in ((".agents/rules", "rules"), (".agents/workflows", "workflows"),
                       (".agent/rules", "rules"), (".agent/workflows", "workflows")):
        top_dir = root / base
        if top_dir.is_dir() and not top_dir.is_symlink():
            for f in top_dir.iterdir():
                if f.is_file() and usable(f) and (kind, f.name) in sources:
                    remove.add(str(f.relative_to(root)))
    for rel in (".agents/README.md", ".agent/README.md", ".agents/skills/README.md", ".claude/skills/README.md"):
        path = root / rel
        if path.is_file() and usable(path) and (has_marker(path) or ("skills", "README.md") in sources):
            remove.add(rel)
    for name in ("AGENTS.md", "CLAUDE.md"):
        path = root / name
        if path.is_file() and usable(path) and has_marker(path, first_line_only=True):
            remove.add(name)

    def covered(rel):
        return any(rel == r or rel.startswith(r + "/") for r in remove)

    files = set()
    for r in remove:
        p = root / r
        files.update([r] if p.is_file() or p.is_symlink() else
                     (str(f.relative_to(root)) for f in p.rglob("*") if f.is_symlink() or not f.is_dir()))

    leftovers = list(rejected)
    for base in SCAN_DIRS:
        top_dir = root / base
        if top_dir.is_symlink():
            leftovers.append(base + " (symlink, not followed)")
            continue
        if top_dir.is_dir():
            for f in top_dir.rglob("*"):
                rel = str(f.relative_to(root))
                if (f.is_symlink() or not f.is_dir()) and not is_tracked(rel) and not covered(rel) and not rel.startswith(KEEP_PREFIXES):
                    leftovers.append(rel)
    for name in ("AGENTS.md", "CLAUDE.md"):
        if (root / name).is_file() and not is_tracked(name) and name not in remove:
            leftovers.append(name)
    return remove, files, leftovers, source


def sweep(root):
    for base in SCAN_DIRS:
        top_dir = root / base
        if top_dir.is_dir() and not top_dir.is_symlink():
            for d in sorted((p for p in top_dir.rglob("*") if p.is_dir() and not p.is_symlink()),
                            key=lambda p: len(p.parts), reverse=True):
                if not any(d.iterdir()):
                    d.rmdir()
            if not any(top_dir.iterdir()):
                top_dir.rmdir()


def main(argv=None):
    parser = argparse.ArgumentParser(description="Remove Promptherder's generated output from a checkout.")
    parser.add_argument("checkout")
    parser.add_argument("--apply", action="store_true", help="remove the listed files (default: preview)")
    args = parser.parse_args(argv)
    root = pathlib.Path(args.checkout).resolve()
    if not root.is_dir():
        sys.exit(f"{root}: no such directory")

    remove, files, leftovers, source = plan(root)
    verb = "removing" if args.apply else "would remove"
    for rel in sorted(files):
        print(f"  {verb}: {rel}")
    for rel in sorted(leftovers):
        print(f"  left for you: {rel}")
    if args.apply:
        for rel in sorted(remove, key=len, reverse=True):
            path = root / rel
            if path.is_dir() and not path.is_symlink():
                shutil.rmtree(path)
            elif path.exists() or path.is_symlink():
                path.unlink()
        sweep(root)
    print(f"{root.name}: manifest from {source}; {verb} {len(files)} files; left for you {len(leftovers)}")
    if not args.apply:
        print("  preview only; run again with --apply to remove")
    if "AGENTS.md" in leftovers:
        print("  AGENTS.md has text above Promptherder's marker: keep that part, delete from the marker line down")


if __name__ == "__main__":
    main()
