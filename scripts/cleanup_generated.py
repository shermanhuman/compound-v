"""Remove Promptherder's generated output from a checkout that is moving to the plugins.

Usage:
    python3 -I scripts/cleanup_generated.py <checkout>           # preview
    python3 -I scripts/cleanup_generated.py <checkout> --apply   # remove

Run it in every existing checkout before pulling (or merging) the change that
retires Promptherder there: the generated files are untracked, so Claude Code and
Codex would keep loading the old skills and rules, and a newly tracked AGENTS.md
or CLAUDE.md can block the pull.

What it removes, and nothing else:
- untracked files the Promptherder manifest lists under .claude/skills/,
  .claude/rules/, .agents/ or .agent/. If the manifest is already gone from the
  working tree, the last committed version in git history is used;
- without any manifest, untracked skill folders named after the old herd skills;
- untracked leftovers of the old herds by name (Antigravity-era .agents/rules/,
  .agents/workflows/, .agents/README.md);
- untracked AGENTS.md / CLAUDE.md that start with the Promptherder marker
  (nothing hand-written above it).
Tracked files, hand-written instructions, .claude/settings*.json and
.claude/worktrees/ are never touched. Anything else left in those folders is
listed for a human. Afterwards `git status --short` should show no `??` under
.claude/ or .agents/; start a new session so the hosts reload.
"""
import json
import pathlib
import shutil
import subprocess
import sys

MARKER = "<!-- Auto-generated by promptherder"
HERD_SKILLS = {
    "compound-v-debug", "compound-v-execute", "compound-v-parallel", "compound-v-persist", "compound-v-pipeline",
    "compound-v-plan", "compound-v-review", "compound-v-tdd", "compound-v-verify", "daisyui", "dockerfile",
    "groq-api", "grugg", "grugg-commit", "grugg-compress", "grugg-help", "grugg-review", "mise", "phoenix",
    "postmark-api", "promptherder", "pull-requests", "release", "rule-browser", "tekmetric-api",
    "telnyx-call-control", "waxseal", "workflow-execute", "workflow-idea", "workflow-plan", "workflow-review",
    "workflow-rule", "workflow-stack",
}
HERD_RULES = {"browser.md", "compound-v.md", "grugg-activate.md", "mise.md", "pull-requests.md",
              "version-bump.md", "no-merge.md", "hard-rules.md", "README.md"}
HERD_WORKFLOWS = {"execute.md", "idea.md", "plan.md", "review.md", "rule.md", "stack.md"}
GENERATED_DIRS = (".claude/skills/", ".claude/rules/", ".agents/", ".agent/")
SCAN_DIRS = (".claude/skills", ".claude/rules", ".agents", ".agent")


def git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)


def load_manifest(root):
    path = root / ".promptherder/manifest.json"
    if path.exists():
        return json.loads(path.read_text()).get("artifacts") or {}, "working tree"
    last = git(root, "log", "-1", "--format=%H", "--", ".promptherder/manifest.json").stdout.strip()
    if last:
        for rev in (last, f"{last}^"):
            shown = git(root, "show", f"{rev}:.promptherder/manifest.json")
            if shown.returncode == 0:
                return json.loads(shown.stdout).get("artifacts") or {}, f"git {rev[:7]}"
    return {}, "none"


def main():
    root = pathlib.Path(sys.argv[1]).resolve()
    apply = "--apply" in sys.argv
    tracked = set(git(root, "ls-files").stdout.split("\n"))

    def is_tracked(rel):
        return rel in tracked or any(f.startswith(rel + "/") for f in tracked)

    artifacts, source = load_manifest(root)
    remove = set()
    for rel in artifacts:
        if rel.startswith(GENERATED_DIRS) and (root / rel).is_file() and not is_tracked(rel):
            remove.add(rel)
    for base in (".claude/skills", ".agents/skills", ".agent/skills"):
        top = root / base
        if top.is_dir():
            for skill in top.iterdir():
                rel = str(skill.relative_to(root))
                if skill.is_dir() and skill.name in HERD_SKILLS and not is_tracked(rel):
                    remove.add(rel)
    for base, names in ((".agents/rules", HERD_RULES), (".agents/workflows", HERD_WORKFLOWS),
                        (".agent/rules", HERD_RULES), (".agent/workflows", HERD_WORKFLOWS)):
        top = root / base
        if top.is_dir():
            for f in top.iterdir():
                rel = str(f.relative_to(root))
                if f.is_file() and f.name in names and not is_tracked(rel):
                    remove.add(rel)
    for rel in (".agents/README.md", ".agent/README.md", ".agents/skills/README.md", ".claude/skills/README.md"):
        if (root / rel).is_file() and not is_tracked(rel):
            remove.add(rel)
    for name in ("AGENTS.md", "CLAUDE.md"):
        path = root / name
        if path.is_file() and not is_tracked(name):
            lines = path.read_text().splitlines()
            if lines and lines[0].startswith(MARKER):
                remove.add(name)

    def covered(rel):
        return any(rel == r or rel.startswith(r + "/") for r in remove)

    leftovers = []
    for base in SCAN_DIRS:
        top = root / base
        if top.is_dir():
            for f in top.rglob("*"):
                rel = str(f.relative_to(root))
                if f.is_file() and not is_tracked(rel) and not covered(rel) and not rel.startswith(".claude/worktrees/") \
                        and not rel.startswith(".claude/settings"):
                    leftovers.append(rel)
    for name in ("AGENTS.md", "CLAUDE.md"):
        if (root / name).is_file() and not is_tracked(name) and name not in remove:
            leftovers.append(name)

    files = {rel for r in remove for rel in ([r] if (root / r).is_file() else
             [str(f.relative_to(root)) for f in (root / r).rglob("*") if f.is_file()])}
    print(f"{root.name}: manifest from {source}; remove {len(files)} files; left for a human {len(leftovers)}")
    for rel in sorted(leftovers):
        print(f"  left for a human: {rel}")
    if not apply:
        print("  preview only; run again with --apply to remove")
        return
    for rel in sorted(remove, key=len, reverse=True):
        path = root / rel
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
    for base in SCAN_DIRS:
        top = root / base
        if top.is_dir():
            for d in sorted((p for p in top.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
                if not any(d.iterdir()):
                    d.rmdir()
            if not any(top.iterdir()):
                top.rmdir()
    print(f"  removed {len(files)} files; now check `git status --short` and start a new session")


if __name__ == "__main__":
    main()
